-- invoice_type distinguishes accounts-receivable (SALES: sent to a customer)
-- from accounts-payable (PURCHASE: a vendor bill received) documents, sharing
-- one table/shape rather than splitting into a separate bill/bill_line_item
-- pair - similar to the Odoo account.move/move_type pattern. contact_id references either a
-- customer or vendor contact depending on invoice_type (see
-- contact.is_customer/is_vendor); invoice_number for a PURCHASE row is
-- typically the vendor's own document number, not one we generate.
CREATE TABLE public.invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.business(id),
    contact_id BIGINT NOT NULL REFERENCES public.contact(id),
    invoice_type VARCHAR(20) NOT NULL DEFAULT 'SALES' CHECK (invoice_type IN ('SALES', 'PURCHASE')),
    estimate_id BIGINT REFERENCES public.estimate(id),
    invoice_number VARCHAR(50) NOT NULL,
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    subtotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    total_tax_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    discount_amount DECIMAL(15,2) DEFAULT 0.00,
    total_amount DECIMAL(15,2) NOT NULL,
    paid_amount DECIMAL(15,2) DEFAULT 0.00,
    balance_due DECIMAL(15,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SENT', 'PAID', 'OVERDUE', 'CANCELLED')),
    notes TEXT,
    terms TEXT,
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMP DEFAULT NOW() NOT NULL,
    deleted_at TIMESTAMP
);

CREATE UNIQUE INDEX invoice_business_number_uindex
