-- Generic party record, reusable for both accounts receivable (customers) and
-- accounts payable (vendors) - a party can be either or both, hence the two
-- independent flags rather than a single type enum.
-- estimate.customer_id still keeps its AR-specific name (estimates are
-- inherently a sales-side document, see the estimate table below). invoice
-- and payment generalized to contact_id since both can now represent either
-- AR or AP activity (see invoice.invoice_type / payment.payment_type).
