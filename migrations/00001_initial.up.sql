-- payment_type carries direction (money received from a customer vs money we
-- paid to a vendor) independent of invoice_id, since invoice_id is nullable
-- (a deposit/retainer/on-account payment may exist with no linked invoice, so
-- direction can't always be inferred by joining through to invoice.invoice_type).
CREATE TABLE public.payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.business(id),
    contact_id BIGINT NOT NULL REFERENCES public.contact(id),
    invoice_id BIGINT REFERENCES public.invoice(id),
    payment_type VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (payment_type IN ('RECEIVED', 'MADE')),
    payment_number VARCHAR(50) NOT NULL,
    payment_date DATE NOT NULL,
    amount DECIMAL(15,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('CASH', 'CHECK', 'CREDIT_CARD', 'ACH', 'WIRE', 'OTHER')),
    reference_number VARCHAR(100),
    notes TEXT,
    -- The cash/bank account this payment hit - the other side of the
    -- contact's AR/AP account (contact.ledger_account_id) when posted.
    -- NULL means this payment isn't posted to the ledger.
    ledger_account_id INTEGER REFERENCES public.ledger_account(id),
    -- Set once posted - links back to the GL entry this payment produced.
    ledger_transaction_id BIGINT REFERENCES public.ledger_transaction(id),
    created_by_user_id BIGINT REFERENCES public.app_user(id),
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMP DEFAULT NOW() NOT NULL,
    deleted_at TIMESTAMP
);

