-- End-of-period close: sweeps REVENUE/EXPENSE balances into equity for a closed period, then
-- hard-locks that period so nothing can post or be edited on or before its end date. Two-stage:
-- each REVENUE/EXPENSE account zeroes into a business's Income Summary account, then Income
-- Summary itself zeroes into Retained Earnings - both are ordinary is_system ledger_account rows
-- (EQUITY type) provisioned per business, not special-cased tables, so every closing posting is
-- an ordinary ledger_transaction/ledger_entry pair like any other.
CREATE TABLE public.period_close (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.business(id),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    income_summary_account_id INTEGER NOT NULL REFERENCES public.ledger_account(id),
    retained_earnings_account_id INTEGER NOT NULL REFERENCES public.ledger_account(id),
    closed_at TIMESTAMP DEFAULT NOW() NOT NULL,
    reversed_at TIMESTAMP,
    created_by_user_id BIGINT REFERENCES public.app_user(id),
    CHECK (period_start <= period_end)
);

-- Partial unique index (not just business_id+period_end) so a reversed close's period_end can be
-- reused by a later re-close, while still blocking two simultaneously-active closes on one date.
CREATE UNIQUE INDEX period_close_business_period_end_uindex
    ON public.period_close(business_id, period_end) WHERE reversed_at IS NULL;
CREATE INDEX period_close_business_id_idx ON public.period_close(business_id);
CREATE INDEX period_close_created_by_user_id_idx ON public.period_close(created_by_user_id);

-- Links each ledger_transaction a close generates back to the account it zeroed out, so a
-- close's postings can be located or reversed without pattern-matching on description text.
CREATE TABLE public.period_close_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_close_id BIGINT NOT NULL REFERENCES public.period_close(id),
    ledger_transaction_id BIGINT NOT NULL REFERENCES public.ledger_transaction(id),
    source_account_id INTEGER NOT NULL REFERENCES public.ledger_account(id)
);

CREATE INDEX period_close_entry_period_close_id_idx ON public.period_close_entry(period_close_id);
CREATE INDEX period_close_entry_ledger_transaction_id_idx ON public.period_close_entry(ledger_transaction_id);

-- Hard lock: a business closed through period_close.period_end rejects any
-- ledger_transaction/ledger_entry dated on or before that date. Reads only already-committed
-- period_close rows, so a close's own entries - inserted before its period_close row exists -
-- are never blocked by the close they belong to.
CREATE FUNCTION public.enforce_period_lock() RETURNS TRIGGER AS $$
DECLARE
    v_business_id BIGINT;
    v_txn_date DATE;
    v_locked_through DATE;
BEGIN
    IF TG_TABLE_NAME = 'ledger_transaction' THEN
        v_business_id := NEW.business_id;
        v_txn_date := NEW.transaction_date;
    ELSE
        SELECT business_id, transaction_date INTO v_business_id, v_txn_date
        FROM public.ledger_transaction WHERE id = NEW.ledger_transaction_id;
    END IF;

    SELECT MAX(period_end) INTO v_locked_through
    FROM public.period_close
    WHERE business_id = v_business_id AND reversed_at IS NULL;

    IF v_locked_through IS NOT NULL AND v_txn_date <= v_locked_through THEN
        RAISE EXCEPTION 'business % is closed through %, cannot post or modify a transaction dated %',
            v_business_id, v_locked_through, v_txn_date;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ledger_transaction_period_lock
    BEFORE INSERT OR UPDATE OF transaction_date, business_id ON public.ledger_transaction
    FOR EACH ROW EXECUTE FUNCTION public.enforce_period_lock();

CREATE TRIGGER ledger_entry_period_lock
    BEFORE INSERT OR UPDATE OF debit_amount, credit_amount, account_id, deleted_at ON public.ledger_entry
    FOR EACH ROW EXECUTE FUNCTION public.enforce_period_lock();

