-- Balance-sheet placement (asset/liability/equity/revenue/expense) is already
-- derivable from ledger_account_type + normal_balance above, so no separate
-- table is needed for that. Cash-flow classification (Operating/Investing/
-- Financing) is not derivable from account_type, hence this dedicated table.
CREATE TABLE public.cash_flow_category (
    id INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    display_sequence INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE public.ledger_account (
    id INTEGER PRIMARY KEY,
