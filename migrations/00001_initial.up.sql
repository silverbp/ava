-- Polymorphic store for AI-generated context (summaries, categorization hints,
-- anomaly flags, user notes) tied to any entity (customer, ledger_transaction,
-- ledger_account, invoice, ...), so a future Claude Code session (via the MCP
-- server) can retrieve prior context about an entity it's working on. No FK on
-- entity_id since it spans multiple target tables. `source`/`metadata` can
-- carry an MCP session/conversation identifier without needing dedicated
-- columns for it.
--
-- Append-only by convention: rows are never edited in place. As granular
-- context accumulates for an entity, a batch of old rows can be rolled up
-- into a single new row (typically context_type = 'summary') with
-- superseded_by_id set on the old rows pointing at it, so retrieval can
-- default to `WHERE superseded_by_id IS NULL` (current context only) while
-- the full trail remains queryable for audit. Genuinely low-value or expired
-- rows are pruned via the existing deleted_at soft-delete; retention policy
-- (what/when to prune) is an application/job concern, not schema.
CREATE TABLE public.entity_context (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.business(id),
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    context_type VARCHAR(50) NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB,
    source VARCHAR(100),
    confidence DECIMAL(5,4),
    superseded_by_id BIGINT REFERENCES public.entity_context(id),
    created_by_user_id BIGINT REFERENCES public.app_user(id),
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMP DEFAULT NOW() NOT NULL,
    deleted_at TIMESTAMP
);

CREATE INDEX entity_context_entity_idx ON public.entity_context(entity_type, entity_id);
CREATE INDEX entity_context_business_id_idx ON public.entity_context(business_id);
CREATE INDEX entity_context_superseded_by_id_idx ON public.entity_context(superseded_by_id);
CREATE INDEX entity_context_created_by_user_id_idx ON public.entity_context(created_by_user_id);

