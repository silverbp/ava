CREATE UNIQUE INDEX ledger_account_business_code_uindex
    ON public.ledger_account(business_id, code);
-- Opening balances are not a column here: model them as a ledger_transaction/ledger_entry
-- pair against a system "Opening Balance Equity" account (is_system = true) instead,
-- keeping the ledger strictly double-entry with no special-cased balance field.
-- Running balances are likewise not cached on this table; compute by aggregating
-- ledger_entry per account, and revisit only if query performance demands a cache.
CREATE UNIQUE INDEX ledger_account_business_parent_name_uindex
    ON public.ledger_account(business_id, COALESCE(parent_account_id, 0), name);

